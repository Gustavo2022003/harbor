import AppKit
import ApplicationServices

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?
    var paths: [String]?
    var appBundleID: String?
    var date: Date
    var pinned = false
}

/// Histórico da área de transferência (⌘C). Clicar num item cola no app em uso.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var accessibilityTrusted = AXIsProcessTrusted()

    /// Fecha o notch antes de colar (definido pelo controller).
    var closeNotch: (() -> Void)?

    private let maxItems = 60
    private let key = "nook.clipboard"
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imageCache = NSCache<NSString, NSImage>()
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private lazy var dir: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let d = base.appendingPathComponent("Harbor/clips", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }()

    /// Fixados primeiro, depois do mais recente para o mais antigo.
    var sortedItems: [ClipItem] {
        items.sorted { a, b in a.pinned != b.pinned ? a.pinned : a.date > b.date }
    }

    init() {
        if let d = UserDefaults.standard.data(forKey: key),
           let v = try? JSONDecoder().decode([ClipItem].self, from: d) {
            items = v
        }
    }

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: - Captura

    private func check() {
        let trusted = AXIsProcessTrusted()
        if trusted != accessibilityTrusted { accessibilityTrusted = trusted }

        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }

        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let now = Date()

        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(ClipItem(kind: .files, paths: urls.map(\.path), appBundleID: app, date: now))
        } else if let s = pb.string(forType: .string),
                  !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(kind: .text, text: String(s.prefix(50_000)), appBundleID: app, date: now))
        } else if let img = NSImage(pasteboard: pb), let file = saveImage(img) {
            insert(ClipItem(kind: .image, imageFile: file, appBundleID: app, date: now))
        }
    }

    private func insert(_ item: ClipItem) {
        var item = item
        if let i = items.firstIndex(where: { sameContent($0, item) }) {
            item.pinned = items[i].pinned
            item.id = items[i].id
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func sameContent(_ a: ClipItem, _ b: ClipItem) -> Bool {
        guard a.kind == b.kind else { return false }
        switch a.kind {
        case .text: return a.text == b.text
        case .files: return a.paths == b.paths
        case .image: return false
        }
    }

    private func trim() {
        let unpinned = items.filter { !$0.pinned }.sorted { $0.date > $1.date }
        guard unpinned.count > maxItems else { return }
        for old in unpinned.dropFirst(maxItems) {
            deleteFiles(of: old)
            items.removeAll { $0.id == old.id }
        }
    }

    // MARK: - Ações

    /// Coloca o item na área de transferência e, se possível, cola no app em uso.
    /// Retorna `true` se colou automaticamente.
    @discardableResult
    func paste(_ item: ClipItem) -> Bool {
        copy(item)
        guard AXIsProcessTrusted() else { return false }
        closeNotch?()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) { Self.sendCommandV() }
        return true
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text:
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let img = image(for: item) { pb.writeObjects([img]) }
        case .files:
            pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        }
        lastChange = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            items[i].date = Date()
            save()
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        deleteFiles(of: item)
        items.removeAll { $0.id == item.id }
        save()
    }

    func clearUnpinned() {
        items.filter { !$0.pinned }.forEach(deleteFiles)
        items.removeAll { !$0.pinned }
        save()
    }

    func requestAccessibility() {
        let opts = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        accessibilityTrusted = AXIsProcessTrustedWithOptions(opts)
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let f = item.imageFile else { return nil }
        if let c = imageCache.object(forKey: f as NSString) { return c }
        guard let img = NSImage(contentsOf: dir.appendingPathComponent(f)) else { return nil }
        imageCache.setObject(img, forKey: f as NSString)
        return img
    }

    // MARK: - Internos

    private static func sendCommandV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let down = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: true) // tecla V
        let up = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private func saveImage(_ img: NSImage) -> String? {
        guard let tiff = img.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        do {
            try png.write(to: dir.appendingPathComponent(name))
            return name
        } catch {
            return nil
        }
    }

    private func deleteFiles(of item: ClipItem) {
        guard let f = item.imageFile else { return }
        imageCache.removeObject(forKey: f as NSString)
        try? FileManager.default.removeItem(at: dir.appendingPathComponent(f))
    }

    private func save() {
        if let d = try? JSONEncoder().encode(items) { UserDefaults.standard.set(d, forKey: key) }
    }
}
